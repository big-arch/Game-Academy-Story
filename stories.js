export const clientFor = (order, id) => CLIENTS[order]?.find(c => c.id === id) || null;
// Новый клиент для заказа — не тот же, что был в прошлый раз.
export function pickClient(order, previous) {
  const pool = (CLIENTS[order] || []).filter(c => c.id !== previous && !c.shelf);
  return pool.length ? pool[Math.floor(Math.random() * pool.length)].id : null;
}
